"""Tab 7: the config files the installer manages - open in your editor, view, diff, create.

Three kinds of file: ``yours`` (installed once from an example, never overwritten),
``rendered`` (regenerated from the repo on every install, so edit the repo source instead)
and ``synced`` (blocks inside are regenerated by ``sync-agents rules``). The repo source of a
row is rendered with the current config before it is diffed or copied, so the comparison shows
what the installer would actually write.
"""

from __future__ import annotations

import curses
import difflib
import os
from dataclasses import dataclass
from typing import Optional, Sequence, Tuple

from installer.core import editor, render, rewrite
from installer.tui import draw
from installer.tui.base import POP, Screen
from installer.tui.listmodel import ListModel

MAX_VIEW_BYTES = 2 * 1024 * 1024
ESC = 27
ENTER_KEYS = (10, 13, curses.KEY_ENTER)
DETAIL_LINES = 3
Styled = Tuple[str, str]  # (text, attr name)


@dataclass(frozen=True)
class FileSpec:
    label: str
    home: str  # attribute of Paths holding the directory
    name: str  # file name inside that directory
    kind: str  # yours | rendered | synced
    source: Optional[str]  # repo-relative POSIX path of the example / template
    note: str


SPECS: Tuple[FileSpec, ...] = (
    FileSpec("~/.claude/CLAUDE.md", "claude_home", "CLAUDE.md", "yours", "claude-code/CLAUDE.md",
             "installed once from the example; never overwritten"),
    FileSpec("~/.agents/LOCAL.md", "agents_home", "LOCAL.md", "yours", "shared/LOCAL.example.md",
             "your personal rules; imported by Claude, synced into Codex, never overwritten"),
    FileSpec("~/.agents/config.json", "agents_home", "config.json", "yours", "shared/config.example.json",
             "central installer config; the Settings tab edits it"),
    FileSpec("~/.codex/AGENTS.md", "codex_home", "AGENTS.md", "synced", "codex/AGENTS.md",
             "the shared and local rule blocks are regenerated by sync-agents rules"),
    FileSpec("~/.claude/settings.json", "claude_home", "settings.json", "yours", "claude-code/settings.example.json",
             "installed once from the example; never overwritten"),
    FileSpec("~/.codex/config.toml", "codex_home", "config.toml", "yours", "codex/config.example.toml",
             "installed once from the example; never overwritten"),
    FileSpec("~/.agents/RULES.md", "agents_home", "RULES.md", "rendered", "shared/RULES.md",
             "rendered on every install: edits are overwritten, edit shared/RULES.md in the repo"),
)


@dataclass(frozen=True)
class FileRow:
    spec: FileSpec
    path: str
    exists: bool


def scan_rows(paths) -> Tuple[FileRow, ...]:
    """One row per spec with the real location (honours relocated tool homes) and existence."""
    rows = []
    for spec in SPECS:
        path = os.path.join(getattr(paths, spec.home), spec.name)
        rows.append(FileRow(spec, path, os.path.isfile(path)))
    return tuple(rows)


def source_text(app, rel: str) -> str:
    """Repo file `rel` as install.sh would write it: templates rendered, rewrite rules applied."""
    with open(os.path.join(app.paths.repo_dir, *rel.split("/")), encoding="utf-8") as fh:
        text = fh.read()
    if render.is_template(text) or rel in render.ALWAYS_TEMPLATE:
        text, _ = render.render_text(text, app.context, rel)
    return rewrite.rewrite(rel, text, app.context)


def read_installed(path: str) -> str:
    """Up to MAX_VIEW_BYTES of the file, decoded as UTF-8 with replacement characters."""
    with open(path, "rb") as fh:
        raw = fh.read(MAX_VIEW_BYTES + 1)
    text = raw[:MAX_VIEW_BYTES].decode("utf-8", errors="replace")
    return text + ("\n[truncated at 2 MB]\n" if len(raw) > MAX_VIEW_BYTES else "")


def diff_style(line: str) -> str:
    """Attr name for one unified-diff line."""
    if line.startswith(("+++", "---")):
        return "title"
    if line.startswith("@@"):
        return "dim"
    return "ok" if line.startswith("+") else "error" if line.startswith("-") else "normal"


def diff_lines(repo_text: str, installed_text: str, rel: str, label: str) -> Tuple[Styled, ...]:
    """Unified diff repo -> installed (so + lines are what you changed), coloured by prefix."""
    diff = difflib.unified_diff(repo_text.splitlines(), installed_text.splitlines(),
                                fromfile=f"repo: {rel}", tofile=f"installed: {label}", lineterm="")
    out = [(line, diff_style(line)) for line in diff]
    return tuple(out) if out else (("(identical to the repo source)", "ok"),)


class TextPaneScreen(Screen):
    """Read-only scrollable text; ``Esc`` closes it (``q`` too, through the App)."""

    tab = None

    def __init__(self, title: str, lines: Sequence[Styled]) -> None:
        self.title = title
        self.lines: Tuple[Styled, ...] = tuple(lines)
        self._top = 0
        self._left = 0
        self._height = 1

    def draw(self, stdscr, app) -> None:
        y0, x0, height, width = draw.draw_frame(stdscr, app, self.title,
                                                "j/k PgUp/PgDn scroll   h/l sideways   q back")
        self._height = height
        self._top = draw.clamp_top(self._top, len(self.lines), height)
        shown = [(text, draw.attr(name)) for text, name in self.lines]
        draw.draw_text(stdscr, y0, x0, height, width, shown, self._top, self._left)

    def handle_key(self, key: int, app) -> Optional[str]:
        try:
            if key == ESC:
                return POP
            if key in (ord("h"), curses.KEY_LEFT):
                self._left = max(0, self._left - 8)
            elif key in (ord("l"), curses.KEY_RIGHT):
                self._left += 8
            else:
                moved = draw.scroll_key(key, self._top, len(self.lines), self._height)
                self._top = self._top if moved is None else moved
        except Exception as exc:  # noqa: BLE001
            app.set_message(f"error: {type(exc).__name__}: {exc}")
        return None


class FilesScreen(Screen):
    title = "Files"
    tab = 7

    def __init__(self) -> None:
        self.model: ListModel = ListModel()
        self._height = 8

    @property
    def rows(self) -> Tuple[FileRow, ...]:
        return self.model.items

    def refresh(self, app) -> None:
        self.model = self.model.with_items(scan_rows(app.paths))

    def on_enter(self, app) -> None:
        self.refresh(app)

    def on_rescan(self, app) -> None:
        self.refresh(app)

    # ------------------------------------------------------------- draw

    def _row_text(self, row: FileRow, selected: bool, width: int) -> Tuple[str, int]:
        mark = draw.glyph("yes" if row.exists else "no")
        state = "present" if row.exists else "missing"
        text = f" {mark} {row.spec.label:<26}{row.spec.kind:<10}{state:<9}{row.spec.note}"
        return draw.truncate(text, width), draw.attr("normal" if row.exists else "warn")

    def draw(self, stdscr, app) -> None:
        if not self.model.items:
            self.refresh(app)
        footer = "Enter/e edit   v view   d diff vs repo   c create from example   j/k move   q back"
        y0, x0, height, width = draw.draw_frame(stdscr, app, self.title, footer)
        draw.safe_addstr(stdscr, y0, x0, f"   {'File':<26}{'Kind':<10}{'State':<9}Note", draw.attr("title"), width)
        self._height = max(1, height - 1 - DETAIL_LINES)
        draw.draw_list(stdscr, y0 + 1, x0, self._height, width, self.model, self._row_text)
        row = self.model.current()
        if row is not None:
            self._draw_detail(stdscr, y0 + height - DETAIL_LINES, x0, width, app, row)

    def _draw_detail(self, stdscr, y: int, x: int, width: int, app, row: FileRow) -> None:
        source = row.spec.source or "none"
        draw.safe_addstr(stdscr, y, x, f"path: {app.paths.display(row.path)}", draw.attr("dim"), width)
        draw.safe_addstr(stdscr, y + 1, x, f"repo source: {source}", draw.attr("dim"), width)
        draw.safe_addstr(stdscr, y + 2, x, row.spec.note, draw.attr("dim"), width)

    # ------------------------------------------------------------- keys

    def handle_key(self, key: int, app) -> Optional[str]:
        try:
            return self._dispatch(key, app)
        except Exception as exc:  # noqa: BLE001 - a bad key must never crash the app
            app.set_message(f"error: {type(exc).__name__}: {exc}")
            return None

    def _dispatch(self, key: int, app) -> Optional[str]:
        h = self._height
        actions = {ord("e"): self._edit, ord("v"): self._view, ord("d"): self._diff, ord("c"): self._create}
        if key in ENTER_KEYS:
            self._edit(app)
        elif key in actions:
            actions[key](app)
        elif key in (ord("j"), curses.KEY_DOWN):
            self.model = self.model.move(1, h)
        elif key in (ord("k"), curses.KEY_UP):
            self.model = self.model.move(-1, h)
        elif key == ord("g"):
            self.model = self.model.home(h)
        elif key == ord("G"):
            self.model = self.model.end(h)
        return None

    def _current(self, app) -> Optional[FileRow]:
        row = self.model.current()
        if row is None:
            app.set_message("no file selected")
        return row

    def _edit(self, app) -> None:
        row = self._current(app)
        if row is None:
            return
        if not row.exists:
            app.set_message(f"{row.spec.label} does not exist yet: press c to create it from the example")
            return
        argv = editor.resolve_editor(app.config.data, os.environ)
        try:
            with app.suspend():
                code = editor.edit_file(row.path, argv)
        except (OSError, ValueError) as exc:
            app.set_message(f"cannot run {' '.join(argv)}: {exc}")
            return
        if row.spec.name == "config.json":
            app.reload_config()
        self.refresh(app)
        note = "" if row.spec.kind == "yours" else f" Note: {row.spec.note}."
        app.set_message(f"editor exited with status {code}.{note}")

    def _view(self, app) -> None:
        row = self._current(app)
        if row is None:
            return
        if not row.exists:
            app.set_message(f"{row.spec.label} does not exist yet: press c to create it")
            return
        lines = [(line, "normal") for line in read_installed(row.path).splitlines()] or [("(empty file)", "dim")]
        app.push(TextPaneScreen(f"View {row.spec.label}", lines))

    def _diff(self, app) -> None:
        row = self._current(app)
        if row is None:
            return
        if row.spec.source is None:
            app.set_message("this file has no repo source to compare with")
            return
        if not row.exists:
            app.set_message(f"{row.spec.label} does not exist yet: nothing to compare (c creates it)")
            return
        try:
            repo_text = source_text(app, row.spec.source)
        except (OSError, ValueError, render.RenderError) as exc:
            app.set_message(f"cannot read the repo source {row.spec.source}: {exc}")
            return
        lines = diff_lines(repo_text, read_installed(row.path), row.spec.source, row.spec.label)
        app.push(TextPaneScreen(f"Diff {row.spec.label} (repo -> installed)", lines))

    def _create(self, app) -> None:
        row = self._current(app)
        if row is None:
            return
        if row.exists or os.path.lexists(row.path):
            app.set_message(f"{row.spec.label} already exists: it is never overwritten")
            return
        if row.spec.source is None:
            app.set_message("there is no example to create this file from")
            return
        try:
            text = source_text(app, row.spec.source)
            os.makedirs(os.path.dirname(row.path), exist_ok=True)
            with open(row.path, "x", encoding="utf-8", newline="\n") as fh:  # "x": never overwrite
                fh.write(text)
        except FileExistsError:
            app.set_message(f"{row.spec.label} already exists: it is never overwritten")
            return
        except (OSError, ValueError, render.RenderError) as exc:
            app.set_message(f"cannot create {row.spec.label}: {exc}")
            return
        if row.spec.name == "config.json":
            app.reload_config()
        app.rescan()
        self.refresh(app)
        app.set_message(f"created {row.spec.label} from {row.spec.source}")
