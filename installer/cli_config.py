"""Configuration-side commands: caps, sections, config, edit, render, render-tree.

`build_context` is shared with ``cli_system`` (doctor) so every command that needs the
template context builds it the same way.
"""

from __future__ import annotations

import json
import os
import sys
from typing import Any, List, Mapping, Optional, Tuple

from installer.cli_io import (
    EXIT_EXCLUDED, EXIT_FAIL, EXIT_OK, Ctx, confirm, dump_json, emit, failure, glyph,
    print_table, read_text, to_jsonable, usage_error, warn,
)
from installer.core import capabilities, config, editor, git, render, rewrite
from installer.core.paths import Paths

TOOLS: Tuple[str, ...] = ("claude", "codex")
SECTION_ORDER: Tuple[str, ...] = ("shared",) + TOOLS

# edit NAME -> (which home, file name inside it, warning shown before editing)
EDIT_TARGETS = {
    "claude": ("claude_home", "CLAUDE.md", ""),
    "local": ("agents_home", "LOCAL.md", ""),
    "config": ("agents_home", config.CONFIG_FILENAME, ""),
    "agents": ("codex_home", "AGENTS.md",
               "note: the synced blocks in this file are regenerated by 'sync-agents rules'"),
    "settings": ("claude_home", "settings.json", ""),
    "codex-config": ("codex_home", "config.toml", ""),
    "rules": ("agents_home", "RULES.md",
              "note: this file is rendered from the repo; edits are overwritten on the next "
              "install - edit shared/RULES.md in the repo instead"),
}


# ------------------------------------------------------------------ context


def probe_caps(ctx: Ctx, only: Optional[Tuple[str, ...]] = None) -> capabilities.Capabilities:
    return capabilities.probe(env=dict(ctx.env), home=ctx.env.get("HOME"), only=only)


def build_context(ctx: Ctx, cfg: Optional[config.Config] = None,
                  caps: Optional[capabilities.Capabilities] = None) -> Mapping:
    cfg = cfg or config.load(ctx.paths)
    caps = caps or probe_caps(ctx)
    return render.build_context(cfg.data, capabilities.to_context(caps), ctx.paths, ctx.env)


# --------------------------------------------------------------------- caps


def cmd_caps(ctx: Ctx) -> int:
    caps = probe_caps(ctx)
    if ctx.flag("json"):
        dump_json(caps)
        return EXIT_OK
    rows = [(glyph("ok" if c.present else "bad"), c.name, c.version or "", c.detail)
            for c in caps.items.values()]
    print_table(("", "TOOL", "VERSION", "DETAIL"), rows)
    if caps.vaults:
        emit("")
        emit("Obsidian vaults: " + ", ".join(caps.vaults))
    if "git" in caps.items and not caps.present("git"):
        emit("")
        emit(f"git is missing: {git.install_hint()}")
    return EXIT_OK


def cmd_sections(ctx: Ctx) -> int:
    cfg = config.load(ctx.paths)
    caps = probe_caps(ctx, only=TOOLS)
    chosen = ["shared"]
    for tool in TOOLS:
        if capabilities.resolve_tool(config.get(cfg, f"tools.{tool}"), caps.get(tool)):
            chosen.append(tool)
    emit(" ".join(chosen))
    return EXIT_OK


# ------------------------------------------------------------------- config


def format_value(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (list, tuple)):
        return ", ".join(str(v) for v in value) if value else "(none)"
    if isinstance(value, Mapping):
        return json.dumps(to_jsonable(value), indent=2)
    return str(value) if value != "" else '""'


def _config_list(ctx: Ctx, cfg: config.Config) -> int:
    if ctx.flag("json"):
        emit(config.to_json(cfg).rstrip("\n"))
        return EXIT_OK
    state = "" if cfg.exists else "  (file not created yet - showing defaults)"
    emit(f"# {ctx.paths.display(cfg.path)}{state}")
    if cfg.error:
        emit(f"# warning: {cfg.error}")
    width = max(len(s.key) for s in config.SETTINGS)
    for setting in config.SETTINGS:
        emit(f"{setting.key.ljust(width)} = {format_value(config.get(cfg, setting.key))}")
    return EXIT_OK


def _config_get(ctx: Ctx, cfg: config.Config) -> int:
    try:
        emit(format_value(config.get(cfg, ctx.args.key)))
    except KeyError:
        raise usage_error(f"unknown config key: {ctx.args.key}")
    return EXIT_OK


def _changed(cfg: config.Config, key: str, value: Any) -> config.Config:
    """Validated copy of `cfg` with `key` set; bad key or value is a usage error."""
    try:
        return config.with_value(cfg, key, value)
    except (KeyError, ValueError, TypeError) as exc:
        raise usage_error(f"{key}: {exc}")


def _write_change(ctx: Ctx, cfg: config.Config, key: str, value: Any) -> int:
    new = _changed(cfg, key, value)
    old = config.get(cfg, key)
    if config.get(new, key) == old:
        emit(f"{key} is already {format_value(old)}; nothing to do.")
        return EXIT_OK
    emit(f"{key}: {format_value(old)} -> {format_value(config.get(new, key))}")
    emit(f"Will write {ctx.paths.display(cfg.path)} (any existing file is backed up first).")
    if cfg.error:
        emit(f"warning: the current file has a problem ({cfg.error}); it will be replaced.")
    if not confirm(ctx.args):
        emit("Aborted.")
        return EXIT_FAIL
    emit(f"Wrote {ctx.paths.display(config.save(new, ctx.paths))}")
    return EXIT_OK


def _config_set(ctx: Ctx, cfg: config.Config) -> int:
    try:
        setting = config.setting_for(ctx.args.key)
        value = config.parse_value(setting, ctx.args.value)
    except (KeyError, ValueError) as exc:
        raise usage_error(f"{ctx.args.key}: {exc}")
    return _write_change(ctx, cfg, ctx.args.key, value)


def _config_reset(ctx: Ctx, cfg: config.Config) -> int:
    try:
        config.setting_for(ctx.args.key)
        default = config.get(config.Config(config.DEFAULTS, cfg.path, False), ctx.args.key)
    except KeyError:
        raise usage_error(f"unknown config key: {ctx.args.key}")
    return _write_change(ctx, cfg, ctx.args.key, default)


def cmd_config(ctx: Ctx) -> int:
    action = ctx.args.config_action
    cfg = config.load(ctx.paths)
    if action == "path":
        emit(cfg.path)
        return EXIT_OK
    if action == "edit":
        return edit_target(ctx, "config")
    handlers = {"list": _config_list, "get": _config_get, "set": _config_set, "reset": _config_reset}
    return handlers[action](ctx, cfg)


# --------------------------------------------------------------------- edit


def target_path(paths: Paths, name: str) -> str:
    home, filename, _ = EDIT_TARGETS[name]
    return os.path.join(getattr(paths, home), filename)


def edit_target(ctx: Ctx, name: str) -> int:
    path = target_path(ctx.paths, name)
    if not os.path.isfile(path):
        raise failure(f"{ctx.paths.display(path)} does not exist yet; run ./install.sh first")
    note = EDIT_TARGETS[name][2]
    if note:
        emit(note)
    argv = editor.resolve_editor(config.load(ctx.paths).data, dict(ctx.env))
    try:
        code = editor.edit_file(path, argv)
    except OSError as exc:
        raise failure(f"cannot run the editor {' '.join(argv)}: {exc}")
    return EXIT_OK if code == 0 else EXIT_FAIL


def cmd_edit(ctx: Ctx) -> int:
    return edit_target(ctx, ctx.args.target)


# ------------------------------------------------------------------- render


def _repo_rel(paths: Paths, path: str) -> Optional[str]:
    """POSIX path of `path` relative to the repo, or None when it is outside the repo.

    Both sides are resolved through symlinks first, so a symlinked checkout (or macOS's
    /var -> /private/var) cannot make an in-repo file look like it lies outside.
    """
    repo = os.path.realpath(paths.repo_dir)
    try:
        rel = os.path.relpath(os.path.realpath(path), repo)
    except ValueError:  # different drive on Windows
        return None
    if rel == os.pardir or rel.startswith(os.pardir + os.sep) or os.path.isabs(rel):
        return None
    return rel.replace(os.sep, "/")


def _requirement_text(names: Tuple[str, ...], mode: str) -> str:
    return "requires " + (" or " if mode == "any" else " and ").join(names)


def _folders_up_to_repo(paths: Paths, path: str) -> List[str]:
    """Directories from the file's own folder up to (and including) the repo root.

    `path` must already be resolved (``os.path.realpath``), like the repo root used here.
    """
    stop = os.path.realpath(paths.repo_dir)
    folder, found = os.path.dirname(path), []
    while folder == stop or folder.startswith(stop + os.sep):
        found.append(folder)
        folder = os.path.dirname(folder)
    return found


def _unmet_requirement(paths: Paths, path: str, text: str, context: Mapping) -> Optional[str]:
    """Reason the file would be left out (its own marker, or a .installer-requires above it)."""
    names, mode = render.requires_of(text)
    if not render.requirements_met(names, mode, context):
        return _requirement_text(names, mode)
    for folder in _folders_up_to_repo(paths, path):
        marker = os.path.join(folder, render.REQUIRES_FILE)
        if not os.path.isfile(marker):
            continue
        dir_names, dir_mode = render.parse_requires_file(read_text(marker, None))
        if not render.requirements_met(dir_names, dir_mode, context):
            return _requirement_text(dir_names, dir_mode)
    return None


def _drop_requires_lines(text: str) -> str:
    lines = text.split("\n")
    keep = [line for index, line in enumerate(lines)
            if not (index < render.HEADER_LINES and render.REQUIRES_MARKER in line)]
    return "\n".join(keep)


def _render_file(text: str, rel: str, context: Mapping) -> Tuple[str, Tuple[str, ...]]:
    try:
        if render.is_template(text) or rel in render.ALWAYS_TEMPLATE:
            out, warnings = render.render_text(text, context, rel)
        else:
            out, warnings = _drop_requires_lines(text), ()
    except render.RenderError as exc:
        raise failure(str(exc))
    return rewrite.rewrite(rel, out, context), warnings


def cmd_render(ctx: Ctx) -> int:
    path = os.path.realpath(ctx.args.file)  # symlinks and the cwd resolved, like the repo root
    if not os.path.isfile(path):
        raise usage_error(f"{ctx.args.file}: no such file")
    rel = _repo_rel(ctx.paths, path)
    if rel is None:
        raise usage_error(f"{ctx.args.file}: outside the repo ({ctx.paths.repo_dir}); "
                          "render only reads files of the repo it was pointed at")
    try:
        text = read_text(path, None)
    except OSError as exc:
        raise failure(f"{ctx.args.file}: {exc}")
    context = build_context(ctx)
    reason = _unmet_requirement(ctx.paths, path, text, context)
    if reason:
        warn(f"excluded: {rel} ({reason})")
        return EXIT_EXCLUDED
    out, warnings = _render_file(text, rel, context)
    for item in warnings:
        warn(f"warning: {item}")
    sys.stdout.write(out)
    return EXIT_OK


def _print_report(report: render.RenderReport) -> None:
    emit(f"rendered {len(report.rendered)}, copied {len(report.copied)}, "
         f"excluded {len(report.excluded)}, warnings {len(report.warnings)}")
    for rel, reason in report.excluded:
        emit(f"  excluded {rel}: {reason}")
    for item in report.warnings:
        warn(f"warning: {item}")


def cmd_render_tree(ctx: Ctx) -> int:
    src, out = os.path.abspath(ctx.args.src), os.path.abspath(ctx.args.out)
    context = build_context(ctx)
    try:
        report = render.render_tree(src, out, context, ctx.args.rel)
    except (render.RenderError, OSError) as exc:
        raise failure(str(exc))
    if ctx.flag("json"):
        dump_json(report)
    else:
        _print_report(report)
    return EXIT_OK
