"""Shared value types. Every module in installer/ codes against these.

All types are frozen dataclasses (immutable). Collections inside them are
tuples or read-only mappings so a status snapshot can never be mutated in
place; derive a new one instead.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum
from types import MappingProxyType
from typing import Mapping, Optional, Tuple

# The three skill scopes. "shared" installs once under ~/.agents/skills and is
# symlinked into the two consumers; "claude" and "codex" are real directories
# that exist only for the platform-specific skill variants.
SCOPES: Tuple[str, ...] = ("shared", "claude", "codex")
CONSUMERS: Tuple[str, ...] = ("claude", "codex")

# Directory names (under a tool's skills dir) that a tool manages itself.
# They are never catalogued, installed, updated or retired.
IGNORED_DIR_REASONS: Mapping[str, str] = MappingProxyType(
    {
        "synced": "managed by the Claude desktop app (claude.ai skill sync)",
        "learned": "landing directory for skills generated by /learn",
        ".system": "Codex built-in system skills",
    }
)

# Files that never count towards a skill's content digest or file list.
IGNORED_FILE_NAMES: Tuple[str, ...] = (".DS_Store", "Thumbs.db", ".gitkeep")
IGNORED_DIR_NAMES: Tuple[str, ...] = ("__pycache__", ".git", "node_modules")


class State(str, Enum):
    """Where a skill stands relative to the repo."""

    NOT_INSTALLED = "not-installed"  # in the repo, absent on disk
    INSTALLED = "installed"  # on disk and byte-identical to the repo copy
    MODIFIED = "modified"  # on disk but differs from the repo copy
    FOREIGN = "foreign"  # on disk, no repo counterpart in this scope
    IGNORED = "ignored"  # on disk, tool-managed; never touched


class LinkState(str, Enum):
    """State of one consumer entry (~/.claude/skills/<name> or ~/.codex/...)."""

    OK = "ok"  # symlink resolving to ~/.agents/skills/<name>
    MISSING = "missing"  # nothing there
    WRONG_TARGET = "wrong-target"  # symlink, but to somewhere else
    BROKEN = "broken"  # symlink whose target does not exist
    REAL_DIR = "real-dir"  # a real directory shadows the shared skill
    FILE = "file"  # a plain file sits where the link should be


@dataclass(frozen=True)
class SkillMeta:
    """Parsed SKILL.md frontmatter. `fields` holds every key, verbatim."""

    name: Optional[str]
    description: Optional[str]
    fields: Mapping[str, str] = field(default_factory=lambda: MappingProxyType({}))

    @property
    def valid(self) -> bool:
        return bool(self.name) and bool(self.description)


@dataclass(frozen=True)
class SkillSource:
    """A skill as it exists in the repo (the installable artifact)."""

    scope: str
    name: str
    path: str  # absolute repo directory
    meta: SkillMeta
    digest: str  # sha256 hex over sorted (relpath, content) pairs
    files: Tuple[str, ...]  # relative paths, sorted, ignored names excluded
    size_bytes: int

    @property
    def key(self) -> Tuple[str, str]:
        return (self.scope, self.name)


@dataclass(frozen=True)
class InstalledSkill:
    """A directory entry found in one of the three install locations."""

    scope: str
    name: str
    path: str  # the entry itself (may be a symlink)
    kind: str  # "dir" | "symlink" | "broken-symlink" | "file"
    link_target: Optional[str]  # raw readlink() value, symlinks only
    resolved: Optional[str]  # realpath, None when broken
    meta: Optional[SkillMeta]  # None when no readable SKILL.md
    digest: Optional[str]  # None when not a readable directory
    files: Tuple[str, ...]
    size_bytes: int
    ignored_reason: Optional[str] = None  # set when the entry is tool-managed

    @property
    def key(self) -> Tuple[str, str]:
        return (self.scope, self.name)


@dataclass(frozen=True)
class ConsumerLink:
    """How one consumer (claude/codex) sees a shared skill."""

    consumer: str
    path: str  # <consumer skills dir>/<name>
    state: LinkState
    target: Optional[str]  # raw readlink() value when it is a symlink
    expected: str  # the relative target install.sh would create


@dataclass(frozen=True)
class RemoteChange:
    """Upstream commits (not yet pulled) that touch this skill's repo path."""

    upstream: str  # e.g. "origin/main"
    files: Tuple[str, ...]  # repo-relative paths changed in HEAD..upstream
    commits: Tuple[str, ...]  # "abc1234 subject" lines, newest first


@dataclass(frozen=True)
class SkillStatus:
    """One row of the installer's world view. Produced by core.status."""

    scope: str
    name: str
    state: State
    source: Optional[SkillSource]
    installed: Optional[InstalledSkill]
    links: Tuple[ConsumerLink, ...] = ()  # shared scope only, one per consumer
    duplicates: Tuple[str, ...] = ()  # human-readable duplicate notes
    issues: Tuple[str, ...] = ()  # human-readable problems (links, frontmatter)
    remote: Optional[RemoteChange] = None

    @property
    def key(self) -> Tuple[str, str]:
        return (self.scope, self.name)

    @property
    def description(self) -> str:
        meta = self.source.meta if self.source else (self.installed.meta if self.installed else None)
        return (meta.description if meta and meta.description else "") or ""

    @property
    def has_remote_update(self) -> bool:
        return self.remote is not None

    @property
    def has_problem(self) -> bool:
        return bool(self.issues) or bool(self.duplicates)

    @property
    def link_problems(self) -> Tuple[ConsumerLink, ...]:
        return tuple(l for l in self.links if l.state not in (LinkState.OK, LinkState.MISSING))


@dataclass(frozen=True)
class RepoIssue:
    """A problem with the repo catalog itself (not the install)."""

    scope: str
    name: str
    kind: str  # "missing-skill-md" | "missing-frontmatter" | "name-mismatch" | "duplicate-scope"
    message: str


@dataclass(frozen=True)
class GitInfo:
    """Result of core.git.detect(). `available` False => git binary missing."""

    available: bool
    version: Optional[str]
    is_repo: bool
    branch: Optional[str]
    head: Optional[str]  # short sha
    upstream: Optional[str]  # e.g. "origin/main"
    ahead: int
    behind: int
    dirty: bool
    last_fetch: Optional[float]  # epoch seconds of .git/FETCH_HEAD, None if never
    remote_url: Optional[str]
    message: str  # one-line human summary for the banner
    hint: str = ""  # what the user should do (install git, clone, pull...)
    error: Optional[str] = None


@dataclass(frozen=True)
class Operation:
    """One planned filesystem step. Nothing here ever deletes."""

    kind: str  # "mkdir" | "copytree" | "symlink" | "backup" | "unlink-to-backup"
    dst: str
    src: Optional[str] = None
    note: str = ""


@dataclass(frozen=True)
class OpResult:
    op: Operation
    ok: bool
    message: str


@dataclass(frozen=True)
class Counts:
    """Summary numbers for the overview screen, per scope."""

    scope: str
    available: int  # in repo
    installed: int  # State.INSTALLED
    modified: int  # State.MODIFIED
    missing: int  # State.NOT_INSTALLED
    foreign: int
    problems: int  # rows with issues or duplicates
    remote_updates: int
